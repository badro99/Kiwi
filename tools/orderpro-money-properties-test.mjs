import assert from 'node:assert/strict';
import fc from '../app/node_modules/fast-check/lib/fast-check.js';
import harness from './orderpro-reliability-harness.cjs';
const app = harness.payment();
fc.assert(fc.property(fc.integer({ min: 1, max: 9999999 }), fc.integer({ min: 2, max: 12 }), fc.integer({ min: 0, max: 30 }), (bill, guests, pct) => {
  Object.assign(app.scope, { sessionTotal: bill / 100, tipPercent: pct });
  app.scope.splitState.egalCount = guests;
  app.api.refreshSplitUI();
  const label = app.nodes.get('#split-egal-per').textContent;
  app.api.confirmSplit();
  const parts = label.split(' · ').map(s => Math.round(parseFloat(s) * 100));
  assert.equal(parts.length, guests);
  assert.deepEqual(parts, Array.from(app.compute(bill, pct, guests).parts));
  assert.equal(parts.reduce((sum, n) => sum + n, 0), bill + Math.round(bill * pct / 100));
  assert.ok(Math.max(...parts) - Math.min(...parts) <= 1);
  assert.equal(app.messages.pop(), 'toast_split_egal ' + label);
}), { numRuns: 1500, seed: 20261104 });
app.scope.sentLines = [{ qty: 3, unitPrice: 0.1 }, { qty: 1, unitPrice: 0.2 }];
app.scope.splitState.assignments = { 0: 0, 1: 0 };
assert.equal(app.api.personSubtotal(0), 0.5);
Object.assign(app.scope, { sessionTotal: 0.5, tipPercent: 10 });
Object.assign(app.scope.splitState, { mode: 'article', articleCount: 2, selectedPerson: 0 });
app.api.renderSplitArticle();
assert.ok(app.nodes.get('#split-people-tabs').innerHTML.includes('0.55 MAD'));
app.api.confirmSplit();
assert.equal(app.messages.pop(), 'toast_split_egal 0.55 MAD · 0.00 MAD');
delete app.scope.splitState.assignments[1];
app.api.confirmSplit();
assert.equal(app.messages.pop(), 'split_tap_items', 'incomplete allocations cannot confirm an underpayment');
const weighted = app.compute(101, 15, 3, [1, 2, 98]);
assert.equal(weighted.parts.reduce((s, n) => s + n, 0), 116);
console.log('✓ OrderPro: 1500 exact centime splits, balanced shares, preview/confirmation parity and integer person subtotals');
