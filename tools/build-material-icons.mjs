#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════════════════
 * Kiwi · builds assets/material-icons.js from the vendored Material Symbols.
 *
 *   node tools/build-material-icons.mjs           rewrite the runtime and the
 *                                                 mapping table in the audit doc
 *   node tools/build-material-icons.mjs --fetch   also curl every alias target
 *                                                 that is not vendored yet
 *   node tools/build-material-icons.mjs --check   exit 1 if either is stale
 *   node tools/build-material-icons.mjs --ratchet lower tools/data-lucide-baseline.json
 *                                                 to today's counts (never raises)
 *
 * It also writes one SUBSET per light surface (below): the same runtime with
 * only the glyphs that surface's files name. The guest app cannot afford the
 * whole set on a slow phone (design 2027 §19: 60 KB of script, all of it).
 *
 * The source of truth is assets/icons/material/*.svg: Google's Outlined files,
 * byte for byte (see the README there). This script embeds every one of them in
 * the runtime, plus the Lucide → Material table from
 * tools/material-icon-aliases.json, so the ~1 700 `<i data-lucide="…">` call
 * sites keep working while the mapping lives in one place.
 *
 * It replaces tools/build-material-symbols-runtime.mjs, which fetched the
 * ROUNDED style from gstatic at build time: not the set §4 of CLAUDE.md locks,
 * and not the files in the folder the rest of the product reads.
 * ─────────────────────────────────────────────────────────────────────────── */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ICON_DIR = 'assets/icons/material';
export const ALIAS_FILE = 'tools/material-icon-aliases.json';
export const BASELINE_FILE = 'tools/data-lucide-baseline.json';
export const RUNTIME = 'assets/material-icons.js';
export const DOC = 'docs/audits/2026-10-12-icon-migration.md';

/* A subset carries every name its files ask for (iconNamesIn, the same census
   the gate runs) plus `also`. A name it still lacks is not drawn as "?": the
   subset loads the full runtime, named by its script tag's data-full, once,
   and leaves the placeholder for it. */
export const SUBSETS = {
  ordering: {
    out: 'assets/material-icons.ordering.js',
    from: ['OrderPro.html', 'assets/orderpro-page.js', 'assets/orderpro-guest.js', 'assets/orderpro-menu.js', 'assets/orderpro-demo.js', 'assets/orderpro-boutique.js'],
    /* A dish's icon comes from the merchant's menu: the ones the page gives a
       tile colour (ICON_CLASS), and the fallback glyph. */
    also: ['coffee', 'croissant', 'cookie', 'sandwich', 'glass-water', 'utensils', 'help'],
  },
};
const GENERATED = (rel) => rel === RUNTIME || Object.values(SUBSETS).some((x) => x.out === rel);
const DOC_START = '<!-- aliases:start (generated by tools/build-material-icons.mjs) -->';
const DOC_END = '<!-- aliases:end -->';
const outlinedUrl = (n) =>
  `https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsoutlined/${n}/default/24px.svg`;

const read = (rel, root = ROOT) => readFileSync(path.join(root, rel), 'utf8');

/* One filled path on the 0 -960 960 960 grid, nothing else. Anything else is
   either not Material Symbols or a file someone retouched. */
export function parseGlyph(name, svg) {
  if (!/viewBox="0 -960 960 960"/.test(svg)) throw new Error(`${name}.svg: not on the Material 960 grid`);
  const paths = [...svg.matchAll(/<path d="([^"]+)"\s*\/>/g)];
  if (paths.length !== 1) throw new Error(`${name}.svg: expected exactly one <path>, found ${paths.length}`);
  if (/<script|\son[a-z]+=|href=/i.test(svg)) throw new Error(`${name}.svg: carries script or a link`);
  return paths[0][1];
}

export function readGlyphs(root = ROOT) {
  const glyphs = {};
  /* Plain `name.svg` only. The folder also holds the weight / optical-size
     variants (`error.wght500.40.svg`) and the generated `sprite.<surface>.svg`
     (design 2027 §8, tools/build-icon-sprite.js); neither is a name the legacy
     runtime draws, and a sprite holds many paths. */
  for (const file of readdirSync(path.join(root, ICON_DIR)).filter((f) => /^[a-z0-9_]+\.svg$/.test(f)).sort()) {
    const name = file.slice(0, -4);
    glyphs[name] = parseGlyph(name, read(path.join(ICON_DIR, file), root));
  }
  return glyphs;
}

export const readAliases = (root = ROOT) => JSON.parse(read(ALIAS_FILE, root));

/* The rule the runtime applies, exported so the gate applies the same one. */
export function resolve(name, aliases) {
  const n = String(name || '');
  return Object.prototype.hasOwnProperty.call(aliases, n) ? aliases[n] : n.replace(/-/g, '_');
}

export function subsetOf(spec, glyphs, aliases, root = ROOT) {
  const names = new Set(spec.also);
  for (const f of spec.from) for (const x of iconNamesIn(read(f, root))) names.add(x.name);
  const g = {}, a = {};
  for (const n of [...names].sort()) {
    const m = resolve(n, aliases);
    if (!glyphs[m]) continue;
    g[m] = glyphs[m];
    if (Object.prototype.hasOwnProperty.call(aliases, n)) a[n] = m;
  }
  const sorted = {};
  for (const k of Object.keys(g).sort()) sorted[k] = g[k];
  return { glyphs: sorted, aliases: a };
}

export function renderRuntime(glyphs, aliases, subset = '') {
  const sub = (text) => (subset ? text : '');
  return `/*! Kiwi icons · Google Material Symbols, Outlined 400, grade 0, opsz 24.
 * Generated by tools/build-material-icons.mjs from assets/icons/material/*.svg
 * (Apache-2.0, see the LICENSE there). Do not edit by hand: change a vendored
 * file or tools/material-icon-aliases.json, then rerun the script.
 *${sub(`
 * SUBSET "${subset}": only the glyphs its pages name (SUBSETS in the script).
 * A name it lacks loads the full runtime, from this script tag's data-full,
 * once; the placeholder waits for it instead of drawing "?".
 *`)}
 * Renders <i data-icon="print"> (Material name) and the legacy
 * <i data-lucide="printer"> (Lucide name, mapped) as an inline <svg> filled
 * with currentColor. window.lucide.createIcons() stays as a compatibility
 * entry point for the call sites written against Lucide. */
(function () {
  'use strict';
  var GLYPHS = ${JSON.stringify(glyphs)};
  var ALIASES = ${JSON.stringify(aliases)};
  var NS = 'http://www.w3.org/2000/svg';
  var FALLBACK = 'help';
  var NAME = /^[a-z0-9_]+$/;
  var missing = [];
${sub(`  var FULL = (function () {
    var s = document.currentScript || (document.querySelector && document.querySelector('script[data-full]'));
    return (s && s.getAttribute('data-full')) || '';
  })();
  var fullAsked = false;
  function wantFull() {
    if (!FULL) return false;
    if (!fullAsked) {
      fullAsked = true;
      var s = document.createElement('script');
      s.src = FULL;
      s.async = true;
      s.onerror = function () { FULL = ''; render(document); };
      document.head.appendChild(s);
    }
    return true;
  }
`)}
  function resolve(name) {
    var n = String(name || '');
    return Object.prototype.hasOwnProperty.call(ALIASES, n) ? ALIASES[n] : n.replace(/-/g, '_');
  }

  /* An unknown name still draws something (the ? glyph) so a layout never
     collapses, but it is reported once instead of passing for an icon. */
  function glyph(material, asked) {
    if (Object.prototype.hasOwnProperty.call(GLYPHS, material)) return GLYPHS[material];${sub(`
    if (wantFull()) return null;`)}
    if (missing.indexOf(asked) < 0) {
      missing.push(asked);
      if (window.console) console.warn('[KiwiIcon] no Material glyph for "' + asked + '"');
    }
    return GLYPHS[FALLBACK];
  }

  /* data-icon is only a placeholder on <i> (or on the <svg> this file drew
     from one): a <button data-icon> in someone's picker is not ours to replace. */
  function createIcon(element) {
    var legacy = element.hasAttribute('data-lucide');
    var tag = element.tagName.toLowerCase();
    if (!legacy && tag !== 'i' && !(tag === 'svg' && element.hasAttribute('data-material-symbol'))) return;
    var asked = (legacy ? element.getAttribute('data-lucide') : element.getAttribute('data-icon')) || FALLBACK;
    var material = resolve(asked);
    if (tag === 'svg' && element.getAttribute('data-material-symbol') === material) return;
${sub(`    var d = glyph(material, asked);
    if (d === null) return;
`)}
    var svg = document.createElementNS(NS, 'svg');
    for (var i = 0; i < element.attributes.length; i++) {
      var attr = element.attributes[i];
      if (attr.name !== 'data-material-symbol') svg.setAttribute(attr.name, attr.value);
    }
    var classes = (svg.getAttribute('class') || '').split(/\\s+/).filter(Boolean);
    var add = legacy ? ['lucide', 'lucide-' + asked, 'material-symbol'] : ['material-symbol'];
    for (var j = 0; j < add.length; j++) if (classes.indexOf(add[j]) < 0) classes.push(add[j]);
    svg.setAttribute('class', classes.join(' '));
    svg.setAttribute('data-material-symbol', material);
    svg.setAttribute('viewBox', '0 -960 960 960');
    svg.setAttribute('fill', 'currentColor');
    svg.setAttribute('stroke', 'none');
    if (!svg.hasAttribute('width')) svg.setAttribute('width', '24');
    if (!svg.hasAttribute('height')) svg.setAttribute('height', '24');
    if (!svg.hasAttribute('aria-label')) svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('focusable', 'false');

    var shape = document.createElementNS(NS, 'path');
    shape.setAttribute('d', ${subset ? 'd' : 'glyph(material, asked)'});
    svg.appendChild(shape);
    element.replaceWith(svg);
  }

  function render(root) {
    var scope = root && root.querySelectorAll ? root : document;
    var list = scope.querySelectorAll('[data-lucide], i[data-icon], svg[data-icon][data-material-symbol]');
    for (var i = 0; i < list.length; i++) createIcon(list[i]);
  }

  /* For template strings that want the markup rather than a placeholder. The
     name lands inside an attribute, so anything but a plain Material name is
     drawn as the fallback instead of being written out. */
  function svg(name, size, className) {
    var asked = String(name || FALLBACK);
    var material = resolve(asked);
    if (!NAME.test(material)) { glyph('', asked); material = FALLBACK; }
    var px = Number(size) || 24;
    var cls = ' class="material-symbol' + (className ? ' ' + String(className).replace(/"/g, '&quot;') : '') + '"';${sub(`
    var d = glyph(material, asked);
    if (d === null) return '<i data-icon="' + material + '"' + cls + ' width="' + px + '" height="' + px + '" aria-hidden="true"></i>';`)}
    return '<svg' + cls + ' data-material-symbol="' + material + '" viewBox="0 -960 960 960" width="' + px +
      '" height="' + px + '" fill="currentColor" stroke="none" aria-hidden="true" focusable="false"><path d="' +
      ${subset ? 'd' : 'glyph(material, asked)'} + '"></path></svg>';
  }

  window.KiwiIcon = Object.freeze({
    svg: svg,
    render: render,
    resolve: resolve,
    has: function (name) { return Object.prototype.hasOwnProperty.call(GLYPHS, resolve(name)); },
    missing: missing
  });
  window.lucide = { createIcons: function () { render(document); }, icons: Object.freeze({}) };

  var queued = false;
  new MutationObserver(function () {
    if (queued) return;
    queued = true;
    queueMicrotask(function () { queued = false; render(document); });
  }).observe(document.documentElement, { childList: true, subtree: true });
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', function () { render(document); });
  else queueMicrotask(function () { render(document); });
})();
`;
}

export function renderDocTable(aliases) {
  const rows = Object.keys(aliases).sort().map((k) => `| \`${k}\` | \`${aliases[k]}\` |`);
  return [DOC_START, '', '| Lucide name | Material Symbol (Outlined) |', '|---|---|', ...rows, '', DOC_END].join('\n');
}

export function spliceDoc(doc, table) {
  const a = doc.indexOf(DOC_START);
  const b = doc.indexOf(DOC_END);
  if (a < 0 || b < a) throw new Error(`${DOC}: mapping markers not found`);
  return doc.slice(0, a) + table + doc.slice(b + DOC_END.length);
}

/* ── call-site census, shared with tools/material-icons-test.mjs ─────────── */
/* Where icons are written: the root pages, assets/ and the Functions. Not the
   tools (fixtures quote names on purpose), not the generated runtime, not the
   Next export (built elsewhere), not iCloud's « foo 2.js » copies. */
const STALE_COPY = / \d+\.[a-z]+$/i;
function walk(dir, out) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) { if (!['vendor', 'landing', 'node_modules'].includes(entry.name)) walk(full, out); }
    else if (/\.(html|js)$/.test(entry.name) && !STALE_COPY.test(entry.name)) out.push(full);
  }
  return out;
}

export function sourceFiles(root = ROOT) {
  const top = readdirSync(root).filter((f) => f.endsWith('.html') && !STALE_COPY.test(f)).map((f) => path.join(root, f));
  const nested = ['assets', 'functions'].flatMap((d) => walk(path.join(root, d), []));
  return [...top, ...nested]
    .map((f) => path.relative(root, f).split(path.sep).join('/'))
    .filter((f) => !GENERATED(f))
    .sort();
}

export function countDataLucide(text) {
  return (text.match(/data-lucide\s*=/g) || []).length;
}

/* Every icon name a file asks for in a form that can be read without running
   it: literal attributes, the result branches of a dynamic attribute
   (`${ok ? 'check' : 'x'}`, `x.icon || 'help'`), setAttribute, KiwiIcon.svg,
   and the values of a `const …ICONS = { … }` table. Operands of a comparison
   (`m === 'cash'`) are not names and are skipped. */
const BRANCH = /(^|\?|:|\|\||\()\s*\\?['"]([a-z][a-z0-9_-]*)\\?['"](?!\s*(?:===|!==|==|!=))/g;
export function iconNamesIn(text) {
  const out = [];
  const at = (i) => text.slice(0, i).split('\n').length;
  for (const m of text.matchAll(/data-(lucide|icon)\s*=\s*\\?(["'])/g)) {
    const start = m.index + m[0].length;
    const rest = text.slice(start, start + 400);
    const lit = rest.match(/^([a-z0-9_-]+)\\?["']/);
    if (lit) { out.push({ name: lit[1], line: at(m.index), attr: m[1] }); continue; }
    let expr = '';
    if (rest.startsWith('${')) {
      let depth = 0;
      for (let i = 0; i < rest.length; i++) {
        if (rest[i] === '{') depth++;
        else if (rest[i] === '}' && --depth === 0) { expr = rest.slice(2, i); break; }
      }
    } else {
      const concat = rest.match(/^['"]\s*\+\s*([\s\S]*?)\s*\+\s*['"]/);
      if (concat) expr = concat[1];
    }
    for (const b of expr.matchAll(BRANCH)) out.push({ name: b[2], line: at(m.index), attr: m[1] });
  }
  for (const m of text.matchAll(/setAttribute\(\s*['"]data-(lucide|icon)['"]\s*,([^)]*)\)/g)) {
    for (const b of m[2].matchAll(BRANCH)) out.push({ name: b[2], line: at(m.index), attr: m[1] });
  }
  for (const m of text.matchAll(/KiwiIcon\.svg\(\s*['"]([a-z0-9_-]+)['"]/g)) out.push({ name: m[1], line: at(m.index), attr: 'icon' });
  /* Data that a template later pours into data-lucide="${x.icon}": the gym's
     plans, the QR menu's dishes, the waiter's highlights. */
  if (/data-lucide|data-icon|KiwiIcon/.test(text)) {
    for (const m of text.matchAll(/\bicon\s*:\s*(?:[^,}\n]*?\?\s*)?['"]([a-z][a-z0-9_-]*)['"](?:\s*:\s*['"]([a-z][a-z0-9_-]*)['"])?/g)) {
      out.push({ name: m[1], line: at(m.index), attr: 'lucide' });
      if (m[2]) out.push({ name: m[2], line: at(m.index), attr: 'lucide' });
    }
  }
  for (const m of text.matchAll(/const\s+[A-Za-z_]*(?:ICONS|[Ii]cons)\s*=\s*\{([^}]*)\}/g)) {
    for (const v of m[1].matchAll(/:\s*['"]([a-z][a-z0-9_-]*)['"]/g)) out.push({ name: v[1], line: at(m.index), attr: 'lucide' });
  }
  /* A helper that picks the name (`function notificationIcon(type)`): its
     return values. `circle-check` hid there and drew a "?" for months. */
  for (const m of text.matchAll(/function\s+[A-Za-z_$]*Icon[A-Za-z_$]*\s*\([^)]*\)\s*\{/g)) {
    let depth = 0, end = m.index + m[0].length - 1;
    for (; end < text.length; end++) {
      if (text[end] === '{') depth++;
      else if (text[end] === '}' && --depth === 0) break;
    }
    const body = text.slice(m.index, end);
    for (const r of body.matchAll(/return\s+([^;\n]+)/g)) {
      for (const b of ('(' + r[1]).matchAll(BRANCH)) out.push({ name: b[2], line: at(m.index), attr: 'lucide' });
    }
  }
  return out;
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const args = process.argv.slice(2);
  const aliases = readAliases();

  if (args.includes('--fetch')) {
    const vendored = new Set(Object.keys(readGlyphs()));
    for (const name of [...new Set(Object.values(aliases))].sort()) {
      if (vendored.has(name)) continue;
      const res = await fetch(outlinedUrl(name));
      if (!res.ok) { console.error(`✗ ${name}: HTTP ${res.status} — not an Outlined name, pick another`); process.exitCode = 1; continue; }
      writeFileSync(path.join(ROOT, ICON_DIR, name + '.svg'), await res.text());
      console.log(`+ ${ICON_DIR}/${name}.svg`);
    }
  }

  if (args.includes('--ratchet')) {
    const files = sourceFiles();
    const base = JSON.parse(read(BASELINE_FILE));
    const next = {};
    for (const f of Object.keys(base).sort()) {
      const now = files.includes(f) ? countDataLucide(read(f)) : 0;
      if (now > 0) next[f] = Math.min(now, base[f]);
    }
    writeFileSync(path.join(ROOT, BASELINE_FILE), JSON.stringify(next, null, 2) + '\n');
    console.log(`baseline: ${Object.values(next).reduce((a, b) => a + b, 0)} data-lucide in ${Object.keys(next).length} files`);
  }

  const glyphs = readGlyphs();
  const unresolved = [...new Set(Object.values(aliases))].filter((m) => !glyphs[m]);
  if (unresolved.length) {
    console.error(`✗ alias targets not vendored: ${unresolved.join(', ')} — rerun with --fetch`);
    process.exit(1);
  }
  const runtime = renderRuntime(glyphs, aliases);
  const doc = spliceDoc(read(DOC), renderDocTable(aliases));
  const subsets = Object.entries(SUBSETS).map(([name, spec]) => {
    const x = subsetOf(spec, glyphs, aliases);
    return [spec.out, renderRuntime(x.glyphs, x.aliases, name), Object.keys(x.glyphs).length];
  });

  if (args.includes('--check')) {
    const stale = [[RUNTIME, runtime], [DOC, doc], ...subsets].filter(([rel, want]) => !existsSync(path.join(ROOT, rel)) || read(rel) !== want).map(([rel]) => rel);
    if (stale.length) { console.error(`✗ stale: ${stale.join(', ')} — run node tools/build-material-icons.mjs`); process.exit(1); }
    console.log('material icons up to date');
  } else {
    writeFileSync(path.join(ROOT, RUNTIME), runtime);
    writeFileSync(path.join(ROOT, DOC), doc);
    console.log(`${RUNTIME}: ${Object.keys(glyphs).length} glyphs, ${Object.keys(aliases).length} aliases, ${(runtime.length / 1024).toFixed(1)} KB`);
    for (const [rel, text, n] of subsets) {
      writeFileSync(path.join(ROOT, rel), text);
      console.log(`${rel}: ${n} glyphs, ${(text.length / 1024).toFixed(1)} KB`);
    }
  }
}
