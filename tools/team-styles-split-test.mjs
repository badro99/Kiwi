/* Byte-exact style extraction, isolated registration and ordered offline loading. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { gunzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const read = f => fs.readFileSync(f, 'utf8');
const hash = s => createHash('sha256').update(s).digest('hex');
const map = JSON.parse(read('tools/fixtures/team-styles/split.json'));
const original = gunzipSync(fs.readFileSync('tools/fixtures/team-styles/original.js.gz')).toString();
const body = original.slice(map.start, map.end), source = read('assets/team/styles.js');
assert.equal(hash(original), map.sha256);
assert.equal(hash(body), map.bodyHash);
assert.equal(source, map.prefix + body + map.suffix, 'entire wrapper and CSS bytes unchanged');
const core = read('assets/team.js').replace(/^import \{\} from '\.\/team\/styles\.js\?v=\d+';\n/m, '');
assert.equal(core, original.slice(0, map.start) + map.relay + original.slice(map.end), 'only the CSS block becomes a relay');
const window = {};
vm.runInNewContext(source, { window });
assert.deepEqual(Object.keys(window), ['KiwiTeamParts']);
assert.deepEqual(Object.keys(window.KiwiTeamParts), ['styles']);
assert.ok(Object.isFrozen(window.KiwiTeamParts.styles));
const ref = vm.runInNewContext('(function(){' + body + '\nreturn { PAGE_CSS };})()', {});
assert.deepEqual({ ...window.KiwiTeamParts.styles }, { ...ref }, 'same page CSS');
assert.match(read('assets/team.js'), /^import \{\} from '\.\/team\/styles\.js\?v=\d+';/);
assert.match(read('kiwi-sw.js'), /'\/assets\/team\/styles\.js\?v=\d+'/);
assert.ok(require('./stamps.js').scan().get('assets/team/styles.js').sites.some(s => s.kind === 'module' && s.file === 'assets/team.js'));
console.log('✓ team styles: exact move, complete wrapper, frozen isolated namespace, ordered module and offline stamp');
