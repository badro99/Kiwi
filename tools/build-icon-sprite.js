#!/usr/bin/env node
/* Kiwi · build-icon-sprite.js : one sprite per surface, from the vendored glyphs.
 *
 * Design 2027, §8: "tools/build-icon-sprite.js generates
 * assets/icons/material/sprite.<surface>.svg holding only the symbols a surface
 * uses. The shell references it with a ?v= stamp, and it is precached (§21.3)."
 *
 * Input   tools/icon-sprites.json   { surfaces: { <surface>: { icons: [...], scan: [...] } } }
 *         assets/icons/material/    the vendored glyphs, never edited
 * Output  assets/icons/material/sprite.<surface>.svg
 *
 * An icon is named `name` (Outlined, weight 400, grade 0, optical size 24: the
 * file `name.svg`) or `name.style.size` (the variants of §8: style `default` or
 * `wght500`, size 20, 24 or 40: the file `name.style.size.svg`). A variant whose
 * file is not checked in yet draws the default 24 glyph, which is the state the
 * spec accepts (§8, "until a variant is checked in"); the sprite still carries a
 * symbol under the variant's own id, so the markup does not change the day the
 * file lands, only the sprite does.
 *
 * Each <symbol> keeps Material's viewBox "0 -960 960 960" and the glyph's
 * markup byte for byte. The referencing element carries NO viewBox of its own
 * (the revision 5 preview bug; tools/icon-render-test.mjs holds it).
 *
 * `scan` lists folders whose files are read for <k-icon name="..."> with
 * literal names, so a kit file's icon reaches its surface's sprite without a
 * hand-kept list. A name built at run time (${...}) is not scanned; the kit
 * bans runtime asset URLs for the same reason (§21.3).
 *
 *   node tools/build-icon-sprite.js              write every sprite
 *   node tools/build-icon-sprite.js till kds     write these surfaces only
 *   node tools/build-icon-sprite.js --check      exit 1 when a sprite is stale
 *
 * Zero dependencies. CommonJS, like the other .js tools (package.json sets no
 * "type").
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const ICON_DIR = 'assets/icons/material';
const MANIFEST = 'tools/icon-sprites.json';
const STYLES = ['default', 'wght500'];
const SIZES = [20, 24, 40];
const VIEWBOX = '0 -960 960 960';

/* "name" or "name.style.size" -> { key, name, style, size, file } */
function parseIconKey(key) {
  const m = /^([a-z][a-z0-9_]*)(?:\.(default|wght500)\.(20|24|40))?$/.exec(String(key));
  if (!m) throw new Error(`icon "${key}": expected name or name.style.size (style ${STYLES.join('|')}, size ${SIZES.join('|')})`);
  const [, name, style, size] = m;
  return {
    key: String(key), name, style: style || 'default', size: size ? Number(size) : 24,
    file: style ? `${name}.${style}.${size}.svg` : `${name}.svg`,
    fallbackFile: `${name}.svg`,
  };
}

/* §8: optical size matches render size, 20 at 20, 24 at 24, 40 at 32 and 40.
   16 px sits inline with 13 px text and takes the smallest file there is. */
function opticalSize(px) {
  const n = Number(px);
  return n <= 20 ? 20 : n <= 24 ? 24 : 40;
}

/* The glyph of one vendored file: the markup between <svg ...> and </svg>,
   untouched. Refuses anything that is not a Material Symbols file. */
function readGlyph(root, file) {
  const p = path.join(root, ICON_DIR, file);
  const svg = fs.readFileSync(p, 'utf8');
  const m = /^\s*<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/.exec(svg);
  if (!m) throw new Error(`${file}: not a single <svg> element`);
  if (!new RegExp(`viewBox="${VIEWBOX}"`).test(m[1])) throw new Error(`${file}: not on the Material 960 grid (viewBox "${VIEWBOX}")`);
  if (/<script|\son[a-z]+\s*=|href\s*=/i.test(svg)) throw new Error(`${file}: carries script or a link`);
  const inner = m[2].trim();
  if (!/^<path d="[^"]+"\s*\/>$/.test(inner)) throw new Error(`${file}: expected exactly one <path d="..."/>`);
  return inner;
}

/* Resolve one icon to the markup its symbol holds. */
function resolveGlyph(root, icon) {
  if (fs.existsSync(path.join(root, ICON_DIR, icon.file))) return { markup: readGlyph(root, icon.file), from: icon.file };
  if (icon.file !== icon.fallbackFile && fs.existsSync(path.join(root, ICON_DIR, icon.fallbackFile))) {
    return { markup: readGlyph(root, icon.fallbackFile), from: icon.fallbackFile, fellBack: true };
  }
  throw new Error(`icon "${icon.key}": ${ICON_DIR}/${icon.fallbackFile} is not vendored (README: the one-line curl; a 404 means the name is not in Outlined)`);
}

function renderSprite(surface, entries) {
  const lines = entries.map((e) => `<symbol id="${e.id}" viewBox="${VIEWBOX}">${e.markup}</symbol>`);
  return `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true"><!-- Generated by tools/build-icon-sprite.js for the "${surface}" surface from ${ICON_DIR}/ (Google Material Symbols, Apache 2.0, see LICENSE there), glyphs byte for byte. Do not edit: change tools/icon-sprites.json and run the tool. -->\n${lines.join('\n')}\n</svg>\n`;
}

function walk(dir, out) {
  if (!fs.existsSync(dir)) return out;
  for (const d of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, d.name);
    if (d.isDirectory()) { if (d.name !== 'node_modules') walk(p, out); }
    else if (/\.(js|mjs|html|css)$/.test(d.name) && !/ 2\./.test(d.name)) out.push(p);
  }
  return out;
}

/* Literal <k-icon name="x" [size="N"] [weight="500"]> in the folders `scan` lists. */
function scanNames(root, dirs) {
  const found = new Set();
  for (const dir of dirs || []) {
    for (const file of walk(path.join(root, dir), [])) {
      const text = fs.readFileSync(file, 'utf8');
      for (const m of text.matchAll(/<k-icon\b([^>]*)>/g)) {
        const attrs = m[1];
        const name = /\bname="([a-z][a-z0-9_]*)"/.exec(attrs);
        if (!name || attrs.includes('${')) continue;
        const size = /\bsize="(\d+)"/.exec(attrs);
        const weight = /\bweight="(\d+)"/.exec(attrs);
        const optical = size ? opticalSize(size[1]) : 24;
        const style = weight && weight[1] === '500' ? 'wght500' : 'default';
        found.add(optical === 24 && style === 'default' ? name[1] : `${name[1]}.${style}.${optical}`);
      }
    }
  }
  return [...found];
}

function readManifest(root) {
  const m = JSON.parse(fs.readFileSync(path.join(root, MANIFEST), 'utf8'));
  if (!m || typeof m.surfaces !== 'object') throw new Error(`${MANIFEST}: expected { surfaces: {...} }`);
  return m;
}

/* -> { <surface>: { file, text, entries, fellBack: [keys] } } */
function build(root = ROOT, only = null) {
  const manifest = readManifest(root);
  const out = {};
  for (const [surface, def] of Object.entries(manifest.surfaces)) {
    if (only && only.length && !only.includes(surface)) continue;
    if (!/^[a-z][a-z0-9-]*$/.test(surface)) throw new Error(`${MANIFEST}: surface "${surface}" must be lower-case letters, digits and dashes`);
    const keys = [...new Set([...(def.icons || []), ...scanNames(root, def.scan)])];
    const entries = [];
    const fellBack = [];
    for (const key of keys.sort()) {
      const icon = parseIconKey(key);
      const g = resolveGlyph(root, icon);
      if (g.fellBack) fellBack.push(key);
      entries.push({ id: icon.key, markup: g.markup, from: g.from });
    }
    out[surface] = { file: `${ICON_DIR}/sprite.${surface}.svg`, text: renderSprite(surface, entries), entries, fellBack };
  }
  return out;
}

function main(argv) {
  const check = argv.includes('--check');
  const only = argv.filter((a) => !a.startsWith('-'));
  const built = build(ROOT, only);
  let stale = 0;
  for (const [surface, s] of Object.entries(built)) {
    const abs = path.join(ROOT, s.file);
    const current = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (check) {
      if (current !== s.text) { stale++; console.log(`✗ ${s.file} is ${current === null ? 'missing' : 'stale'}; run node tools/build-icon-sprite.js ${surface}`); }
      else console.log(`✓ ${s.file} (${s.entries.length} symbols)`);
    } else {
      if (current !== s.text) fs.writeFileSync(abs, s.text);
      console.log(`${current === s.text ? '=' : '+'} ${s.file}  ${s.entries.length} symbols${s.fellBack.length ? `  (default 24 until the variant is vendored: ${s.fellBack.join(', ')})` : ''}`);
    }
  }
  if (!Object.keys(built).length) console.log('no surface matched');
  if (stale) process.exit(1);
}

module.exports = { ROOT, ICON_DIR, MANIFEST, VIEWBOX, parseIconKey, opticalSize, readGlyph, resolveGlyph, renderSprite, scanNames, readManifest, build };

if (require.main === module) main(process.argv.slice(2));
