import briefingSource from './briefing-test-source.cjs';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read = f => fs.readFileSync(f, 'utf8');
const part = process.env.KIWI_Q_PART;
if (!part || part === 'briefing') {
  const memory = new Map();
  const localStorage = { getItem: k => memory.get(k) || null, setItem: (k,v) => memory.set(k,v), removeItem: k => memory.delete(k) };
  const document = { readyState:'loading', documentElement:{lang:'en'}, addEventListener(){}, querySelector(){return null;}, createElement(){return {setAttribute(){}};} };
  const window = { KiwiEnv:{isReal:()=>true}, KiwiAgentTier:()=> 'owner', KiwiCloudDoc:{currentSlug:()=> 'fixture'}, addEventListener(){} };
  vm.runInNewContext(briefingSource(), {window,document,localStorage,console,Date,setTimeout,clearTimeout});
  const B = window.KiwiBriefing, T = B._test;
  const items = [{id:'x',name:'X',tracked:true,balance:6,threshold:5}];
  assert.equal(T.lowStockRule({items}),null);
  assert.equal(typeof B.setSettings,'function','merchant can override thresholds');
  assert.equal(B.setSettings({stockFactor:2}),true);
  assert.ok(T.lowStockRule({items}),'override changes rule outcome');
  const before = JSON.stringify(B.settings());
  for (const value of [{stockFactor:0},{stockFactor:11},{stockFactor:NaN},{stockFactor:'2'},{samples:1.5},{unknown:1}]) assert.equal(B.setSettings(value),false);
  assert.equal(JSON.stringify(B.settings()),before,'invalid edits are atomic');
  const stored = T.read();
  assert.equal(stored.settings.stockFactor,2,'settings share existing briefing document');
  assert.equal(T.mergeDocs({days:[]},stored).settings.stockFactor,2,'cloud merge retains settings');
  const row = T.compute([()=>T.lowStockRule({items})]);
  assert.match(row.lines[0].evidence.source,/Stock threshold multiplier 2/);
  window.KiwiWeather = { isRain:()=>true, rainEffect:()=>({change:.1,rainDays:5,dryDays:10}) };
  const weather = {ok:true,days:[{day:'2099-01-01',precip:3}],log:{}};
  assert.ok(T.weatherRule({weather,today:'2026-10-26'}));
  assert.equal(B.setSettings({weatherEffect:15}),true);
  assert.equal(T.weatherRule({weather,today:'2026-10-26'}),null);
  console.log('Q briefing: overrides, invalid refusal, persistence, evidence and weather passed');
}
if (!part || part === 'vision') {
  const route = read('functions/api/ai/salle-import.js');
  const validate = new Function(route.match(/export function validateSalle\(raw\) \{[\s\S]*?\n\}/)[0].replace('export ', '')+';return validateSalle')();
  const input = {tables:[{shape:'round',seats:2,count:1,row:1,column:1},{shape:'rect',seats:4,count:1,row:0,column:0},{shape:'square',seats:2,count:1,row:1,column:0}]};
  const invalid = validate({tables:[{shape:'round',seats:2,count:1,row:-1,column:Infinity,zone:'secret'}]});
  assert.equal(invalid.tables[0].row,undefined);
  assert.equal(invalid.tables[0].column,undefined);
  assert.equal(invalid.tables[0].zone,undefined);
  const validated = validate(input);
  assert.equal(validated.tables[0].row,1,'model rough placement survives validation');
  const window = {};
  vm.runInNewContext(read('assets/salle-scan.js'),{window});
  const facts = window.KiwiSalleScan._aggregate([validated]);
  assert.equal(facts.placement.length,3);
  vm.runInNewContext(read('assets/floorplan-core.js'),{window,console});
  const plan = window.KiwiFloorCore.generatePlan({...facts, floors:['Room'],dims_default:{w:1200,h:1000}},'dense');
  const round = plan.tables.find(t=>t.type==='round2'), square = plan.tables.find(t=>t.type==='sq2'), rect = plan.tables.find(t=>t.type==='rect4');
  assert.ok(round.x > square.x && round.y === square.y && rect.y < square.y,'photo order survives in suggested plan');
  assert.equal(plan.suggested,true);
  const zoned = window.KiwiSalleScan._aggregate([{tables:[{shape:'round',seats:2,count:1,zone:'back'},{shape:'square',seats:2,count:1,zone:'front'}]},{tables:[{shape:'rect',seats:4,count:1,zone:'middle'}]}]);
  const zonePlan = window.KiwiFloorCore.generatePlan({...zoned,floors:['Room'],dims_default:{w:1200,h:1000}},'confort');
  assert.ok(zonePlan.tables.find(t=>t.type==='round2').y > zonePlan.tables.find(t=>t.type==='sq2').y);
  assert.notEqual(zonePlan.tables.find(t=>t.type==='round2').zone,zonePlan.tables.find(t=>t.type==='rect4').zone,'separate photos retain separate suggested zones');
  assert.match(read('assets/pages/tables-operations.js'),/A\.placement = facts\.placement/,'actual wizard forwards placement');
  assert.match(read('assets/salle-scan.js'),/Plan suggéré à partir de votre photo/);
  for (const text of ['Suggested plan from your photo','مخطط مقترح من صورتك']) assert.ok(read('assets/i18n.js').includes(text));
  console.log('Q vision: model fixture → aggregate → suggested arrangement and multilingual notice passed');
}
