#!/usr/bin/env node
// Writes functions/_fast-routes.js: one entry per static Pages Functions route,
// so the root middleware can call the handler directly instead of letting the
// generated Pages router compile all ~250 route patterns on every request
// (docs/ops/CPU.md, "Route dispatch").
//
//   node tools/build-fast-routes.mjs          rewrite the table
//   node tools/build-fast-routes.mjs --check  exit 1 when the table is stale
//
// The table only lists what is safe to call directly. Anything it leaves out
// still works: the middleware falls back to the normal Pages router.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FN = path.join(ROOT, 'functions');
export const OUT = path.join(FN, '_fast-routes.js');

const HANDLER = /^onRequest(Get|Post|Put|Patch|Delete|Options|Head)?$/;

// Export names a module declares. Pages reads the same names to build routes.
export function handlerExports(src) {
  const names = new Map(); // name -> 'function' | 'array' | 'other'
  for (const m of src.matchAll(/export\s+(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)/g)) names.set(m[1], 'function');
  for (const m of src.matchAll(/export\s+(?:const|let|var)\s+([A-Za-z_$][\w$]*)\s*=\s*(\[)?/g)) names.set(m[1], m[2] ? 'array' : 'other');
  for (const m of src.matchAll(/export\s*\{([^}]*)\}/g)) {
    for (const part of m[1].split(',')) {
      const bits = part.trim().split(/\s+as\s+/);
      const name = (bits[1] || bits[0] || '').trim();
      if (name) names.set(name, 'other');
    }
  }
  return new Map([...names].filter(([n]) => HANDLER.test(n)));
}

function walk(dir, out = []) {
  for (const ent of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(full, out);
    else if (/\.(m?js|ts)$/.test(ent.name)) out.push(full);
  }
  return out;
}

// functions/api/menu.js -> /api/menu ; functions/api/index.js -> /api
function routePathOf(rel) {
  const noExt = rel.replace(/\.(m?js|ts)$/, '');
  const segs = noExt.split('/');
  if (segs[segs.length - 1] === 'index') segs.pop();
  return '/' + segs.join('/');
}

export function buildTable() {
  const files = walk(FN).map(f => path.relative(FN, f).split(path.sep).join('/'));
  const middlewares = [];
  const statics = [];
  const dynamicPrefixes = [];
  const skipped = [];
  for (const rel of files) {
    const src = fs.readFileSync(path.join(FN, rel), 'utf8');
    const exports = handlerExports(src);
    if (!exports.size) continue;
    const base = path.posix.basename(rel).replace(/\.(m?js|ts)$/, '');
    if (base === '_middleware') {
      const dir = '/' + path.posix.dirname(rel).replace(/^\.$/, '');
      const only = [...exports.keys()];
      if (only.length !== 1 || only[0] !== 'onRequest' || exports.get('onRequest') !== 'function') {
        throw new Error(`${rel}: a middleware must export one onRequest function for the fast route table`);
      }
      middlewares.push({ rel, mount: dir === '/' ? '/' : dir.replace(/\/$/, '') });
      continue;
    }
    const route = routePathOf(rel);
    if (/\[/.test(route)) {
      // [[rest]] also matches its bare prefix; [one] needs one more segment.
      dynamicPrefixes.push({ prefix: route.slice(0, route.indexOf('[')).replace(/\/$/, ''), bare: route.includes('[[') });
      continue;
    }
    const kinds = [...exports.values()];
    if (exports.has('onRequest') && exports.size > 1) { skipped.push([route, 'onRequest next to method handlers']); continue; }
    if (kinds.includes('array')) { skipped.push([route, 'handler is an array of functions']); continue; }
    statics.push({ rel, route });
  }
  const seen = new Map();
  for (const s of statics) {
    if (seen.has(s.route)) throw new Error(`two route files serve ${s.route}: ${seen.get(s.route)} and ${s.rel}`);
    seen.set(s.route, s.rel);
  }
  // A dynamic route sorted ahead of a static one could claim the same path, so
  // anything under a dynamic prefix stays with the Pages router.
  const entries = statics.filter(s => {
    const hit = dynamicPrefixes.find(d => (d.bare && s.route === d.prefix) || s.route.startsWith(d.prefix + '/'));
    if (hit) skipped.push([s.route, `under the dynamic route ${hit.prefix}`]);
    return !hit;
  }).sort((a, b) => a.route.localeCompare(b.route));
  const rootMw = middlewares.find(m => m.mount === '/');
  if (!rootMw) throw new Error('functions/_middleware.js must exist: it runs the fast route table');
  const nested = middlewares.filter(m => m.mount !== '/').sort((a, b) => a.mount.split('/').length - b.mount.split('/').length);
  return { entries, nested, skipped };
}

export function render({ entries, nested }) {
  const lines = [
    '// Generated by tools/build-fast-routes.mjs. Do not edit by hand: run',
    '// `node tools/build-fast-routes.mjs` after adding, moving or removing a route.',
    '// Static routes the root middleware may call directly (docs/ops/CPU.md).',
  ];
  nested.forEach((m, i) => lines.push(`import { onRequest as mw${i} } from './${m.rel}';`));
  entries.forEach((e, i) => lines.push(`import * as r${i} from './${e.rel}';`));
  lines.push('');
  lines.push('// Nested middlewares, outermost first, with the path each one covers.');
  lines.push('export const FAST_MIDDLEWARES = [');
  nested.forEach((m, i) => lines.push(`  [${JSON.stringify(m.mount)}, mw${i}],`));
  lines.push('];');
  lines.push('');
  lines.push('/** @type {Map<string, Record<string, any>>} */');
  lines.push('export const FAST_ROUTES = new Map(/** @type {Array<[string, Record<string, any>]>} */ ([');
  entries.forEach((e, i) => lines.push(`  [${JSON.stringify(e.route)}, r${i}],`));
  lines.push(']));');
  return lines.join('\n') + '\n';
}

// Real paths: the hook runs this from a temp export, and macOS reaches /var
// through a symlink, so a plain comparison would silently skip the check.
const real = (p) => { try { return fs.realpathSync(p); } catch (_) { return path.resolve(p); } };
const isMain = process.argv[1] && real(process.argv[1]) === real(fileURLToPath(import.meta.url));
if (isMain) {
  const table = buildTable();
  const text = render(table);
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (current !== text) {
      console.error('functions/_fast-routes.js is stale: run `node tools/build-fast-routes.mjs`');
      process.exit(1);
    }
    console.log(`fast route table current (${table.entries.length} routes)`);
  } else {
    if (current !== text) fs.writeFileSync(OUT, text);
    console.log(`${current === text ? 'unchanged' : 'wrote'} functions/_fast-routes.js: ${table.entries.length} routes, ${table.nested.length} nested middleware, ${table.skipped.length} left to the Pages router`);
    for (const [r, why] of table.skipped) console.log(`  ${r}: ${why}`);
  }
}
