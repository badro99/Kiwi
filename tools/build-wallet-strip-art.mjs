#!/usr/bin/env node
// Writes functions/api/wallet/_strip-art.js: the Kiwi leaf and the Material
// "redeem" icon as small white-on-clear PNG masks, so the pass strip drawn in
// pure JS (_png.js, no canvas, no font) can stamp them onto its coins. The
// shapes come from the vendored SVGs, rasterized once here by headless Chrome.
// Run again only if one of the two source SVGs changes.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const puppeteer = createRequire(path.join(root, 'app/package.json'))('puppeteer-core');
const bin = process.env.KIWI_CHROMIUM_BIN || ['/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/usr/bin/chromium', '/usr/bin/google-chrome'].find(fs.existsSync);
const SIZE = 128;

const white = (svg) => svg.replace(/<\?xml[^>]*>/, '').replace(/<!--[\s\S]*?-->/g, '').replace(/<style>[\s\S]*?<\/style>/, '')
  .replace(/<svg /, `<svg width="${SIZE}" height="${SIZE}" style="display:block;fill:#fff" `).replace(/\sclass="cls-\d"/g, '').replace(/\sfill="[^"]*"/g, '');
const sources = {
  leaf: white(fs.readFileSync(path.join(root, 'assets/kiwi-favicon-new.svg'), 'utf8')),
  redeem: white(fs.readFileSync(path.join(root, 'assets/icons/material/redeem.svg'), 'utf8')),
};

const browser = await puppeteer.launch({ executablePath: bin, headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage();
await page.setViewport({ width: SIZE, height: SIZE, deviceScaleFactor: 1 });
const out = {};
for (const [name, svg] of Object.entries(sources)) {
  await page.setContent(`<!doctype html><html><body style="margin:0;background:transparent">${svg}</body></html>`);
  out[name] = await (await page.$('svg')).screenshot({ encoding: 'base64', omitBackground: true });
}
await browser.close();

const file = path.join(root, 'functions/api/wallet/_strip-art.js');
fs.writeFileSync(file, `// Generated by tools/build-wallet-strip-art.mjs: white-on-clear ${SIZE}px masks
// of the Kiwi leaf (assets/kiwi-favicon-new.svg) and the Material redeem icon
// (assets/icons/material/redeem.svg, Apache 2.0) for the pass strip. Do not edit.
export const masks = ${JSON.stringify(out)};
`);
console.log('wrote', path.relative(root, file), Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])));
