const DICTS = { fr: FR, en: EN, ar: AR };

export function lang() {
  let l = '';
  try { l = (window.KiwiI18n && window.KiwiI18n.getLang && window.KiwiI18n.getLang()) || ''; } catch (_) { l = ''; }
  if (!l) { try { l = localStorage.getItem('kiwiLang') || ''; } catch (_) { l = ''; } }
  return DICTS[l] ? l : 'fr';
}

/* tr('countN', { n: 3 }) : les {marques} sont remplacées par les valeurs. */
export function tr(key, vars) {
  const d = DICTS[lang()];
  let s = (d && d[key]) || FR[key] || '';
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] == null ? m : String(vars[k])));
  return s;
}

